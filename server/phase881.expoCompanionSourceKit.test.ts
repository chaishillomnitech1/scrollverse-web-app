import { describe, expect, it } from "vitest";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../mobile-companion");
const docsRoot = path.resolve(import.meta.dirname, "../docs");

describe("Phase 881 Expo companion source kit", () => {
  it("provides focused native routes and portal handoffs without hardcoding a store identity or submission flow", () => {
    const config = fs.readFileSync(path.join(root, "app.config.ts"), "utf8");
    const packageManifest = fs.readFileSync(path.join(root, "package.json"), "utf8");
    const releasePreflight = fs.readFileSync(path.join(root, "scripts/release-preflight.mjs"), "utf8");
    const tabs = fs.readFileSync(path.join(root, "app/(tabs)/_layout.tsx"), "utf8");
    const portal = fs.readFileSync(path.join(root, "lib/portal.ts"), "utf8");
    const portalCard = fs.readFileSync(path.join(root, "components/PortalCard.tsx"), "utf8");
    const readme = fs.readFileSync(path.join(root, "README.md"), "utf8");
    const qaChecklist = fs.readFileSync(path.join(root, "QA-CHECKLIST.md"), "utf8");
    const releasePacket = fs.readFileSync(path.join(docsRoot, "scrollverse-app-store-owner-packet.md"), "utf8");
    expect(config).toContain('slug: "scrollverse-mobile-companion"');
    expect(config).not.toContain("bundleIdentifier:");
    expect(config).not.toContain("package:");
    expect(packageManifest).toContain('"react-dom": "19.1.0"');
    expect(packageManifest).toContain('"react-native-web": "^0.21.0"');
    expect(packageManifest).toContain('"preflight:release": "node ./scripts/release-preflight.mjs"');
    expect(tabs).toContain('name="index"');
    expect(tabs).toContain('name="omniland"');
    expect(tabs).toContain('name="mirror"');
    expect(tabs).toContain('name="create"');
    expect(tabs).toContain('name="sources"');
    expect(portal).toContain('PORTAL_ORIGIN = "https://scrollverse.co"');
    expect(portal).toContain('mirror: "/chais-sabir-allah-mirror"');
    expect(portal).toContain('create: "/episode-brief-builder"');
    expect(portal).toContain("Linking.canOpenURL(destination)");
    expect(portal).toContain("async function provideHandoffFeedback()");
    expect(portal).toContain("Haptics are optional; a device-specific feedback failure must not block navigation.");
    expect(portal).toContain("await Linking.openURL(destination)");
    expect(portalCard).toContain('accessibilityRole="link"');
    expect(portalCard).toContain("accessibilityHint={hint}");
    expect(portalCard).toContain("Path unavailable — try again");
    expect(portalCard).not.toContain("expo-haptics");
    expect(readme).toContain("does **not** contain a store-bound iOS bundle identifier");
    expect(readme).toContain("Store-release gate");
    expect(readme).toContain("Owner-local device QA");
    expect(readme).toContain("exported for Android and web runtimes");
    expect(qaChecklist).toContain("ScrollVerse Mobile Companion — Owner-Local QA Checklist");
    expect(qaChecklist).toContain("Screen-reader labels");
    expect(qaChecklist).toContain("Release boundary");
    expect(qaChecklist).not.toContain("Apple Developer account password");
    expect(releasePacket).toContain("Current source-kit baseline");
    expect(releasePacket).toContain("Do not prefill “no data collected.”");
    expect(releasePacket).toContain("Final-release rule");
    expect(releasePacket).toContain("App privacy details on the App Store");
    expect(releasePacket).not.toContain("eas submit --platform");
    expect(releasePreflight).toContain("source-only release-gate preflight");
    expect(releasePreflight).toContain("Store-bound iOS and Android identifiers are absent");
    expect(releasePreflight).toContain("No EAS submission profile is configured");
  });
});
